#!/usr/bin/env node
/**
 * Generate docs/reference/mc-cheatsheet.md from bot/cli/registry.mjs.
 *
 * One line per command, grouped by category. Skills include this as the
 * canonical "what mc verbs exist" reference; per-command detail is fetched
 * on demand via `mc <cmd> --help`. This keeps the agent's prompt small.
 *
 * Run:   node scripts/gen-mc-cheatsheet.mjs
 * Output: docs/reference/mc-cheatsheet.md
 *
 * Programmatic:
 *   import { buildCheatsheet, CHEATSHEET_PATH } from './gen-mc-cheatsheet.mjs';
 *   const text = buildCheatsheet(RAW_COMMAND_DEFS);
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CHEATSHEET_PATH = join(ROOT, 'docs/reference/mc-cheatsheet.md');

import { CATEGORY_ORDER as REGISTRY_CATEGORY_ORDER } from '../bot/cli/registry.mjs';

/** Same order as `mc help` / registry `CATEGORY_ORDER`. */
export const CATEGORY_ORDER = REGISTRY_CATEGORY_ORDER;

function compactUsage(cmd) {
  if (cmd.usage) return cmd.usage;
  if (cmd.argSchema?.length) {
    const parts = cmd.argSchema.map((a) => {
      const placeholder = a.key.toUpperCase();
      return a.required ? placeholder : `[${placeholder}]`;
    });
    return `mc ${cmd.name} ${parts.join(' ')}`.trim();
  }
  return `mc ${cmd.name}`;
}

function emitCategory(lines, cat, cmds) {
  lines.push(`## ${cat}`);
  lines.push('');
  for (const cmd of cmds.slice().sort((a, b) => a.name.localeCompare(b.name))) {
    const aliases = cmd.aliases?.length ? ` (${cmd.aliases.join(', ')})` : '';
    const usage = compactUsage(cmd);
    const desc = cmd.description ? ` — ${cmd.description}` : '';
    lines.push(`- \`${usage}\`${aliases}${desc}`);
  }
  lines.push('');
}

/**
 * Render the full mc-cheatsheet.md content from a RAW_COMMAND_DEFS array.
 * Returns the file body as a string (no trailing newline — matches writeFileSync output).
 */
export function buildCheatsheet(rawDefs, categoryOrder = CATEGORY_ORDER) {
  const order = categoryOrder;
  const groups = {};
  for (const cmd of rawDefs) {
    if (!groups[cmd.category]) groups[cmd.category] = [];
    groups[cmd.category].push(cmd);
  }

  const lines = [];
  lines.push('# mc command cheatsheet');
  lines.push('');
  lines.push('One line per command. Use `mc <command> --help` for full detail (args, types, examples).');
  lines.push('');
  lines.push('Generated by `scripts/gen-mc-cheatsheet.mjs` from `bot/cli/registry.mjs`. Do not edit by hand.');
  lines.push('');

  const seenCats = new Set();
  for (const cat of order) {
    if (!groups[cat]) continue;
    seenCats.add(cat);
    emitCategory(lines, cat, groups[cat]);
  }

  // Catch any categories not in CATEGORY_ORDER (emitted in insertion order for stability).
  for (const [cat, cmds] of Object.entries(groups)) {
    if (seenCats.has(cat)) continue;
    emitCategory(lines, cat, cmds);
  }

  return lines.join('\n');
}

async function main() {
  const { RAW_COMMAND_DEFS, CATEGORY_ORDER } = await import(join(ROOT, 'bot/cli/registry.mjs'));
  const text = buildCheatsheet(RAW_COMMAND_DEFS, CATEGORY_ORDER);
  writeFileSync(CHEATSHEET_PATH, text);
  const categories = new Set(RAW_COMMAND_DEFS.map((c) => c.category)).size;
  console.log(`wrote ${CHEATSHEET_PATH} (${RAW_COMMAND_DEFS.length} commands across ${categories} categories)`);
}

// Run main only when invoked as a script (not when imported).
const invokedAsScript = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedAsScript) {
  await main();
}
