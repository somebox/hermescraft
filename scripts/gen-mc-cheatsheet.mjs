#!/usr/bin/env node
/**
 * Generate docs/reference/mc-cheatsheet.md from bot/cli/registry.mjs.
 *
 * Tier layout: Agent core → Extended → Microscope (see registry-surface.mjs).
 * Skills include this as the canonical "what mc verbs exist" reference.
 *
 * Run:   node scripts/gen-mc-cheatsheet.mjs
 * Output: docs/reference/mc-cheatsheet.md
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CHEATSHEET_PATH = join(ROOT, 'docs/reference/mc-cheatsheet.md');

import { CATEGORY_ORDER as REGISTRY_CATEGORY_ORDER } from '../bot/cli/registry.mjs';

export const CATEGORY_ORDER = REGISTRY_CATEGORY_ORDER;

const TIER_ORDER = ['core', 'extended', 'microscope'];
const TIER_HEADINGS = {
  core: 'Agent core',
  extended: 'Extended',
  microscope: 'Microscope',
};

function tierOf(cmd) {
  return cmd.surface ?? 'extended';
}

function compactUsage(cmd) {
  if (cmd.usage) return cmd.usage;
  if (cmd.argSchema?.length) {
    const parts = cmd.argSchema.map((a) => {
      const placeholder = a.key.toUpperCase();
      return a.required ? placeholder : `[${placeholder}]`;
    });
    return `mc ${cmd.name} ${parts.join(' ')}`.trim();
  }
  return `mc ${cmd.name}`;
}

function firstSentence(desc) {
  if (!desc) return '';
  const m = desc.match(/^[^.!?]+[.!?]?/);
  return (m ? m[0] : desc).trim();
}

function emitFullLines(cmds) {
  const lines = [];
  for (const cmd of cmds.slice().sort((a, b) => a.name.localeCompare(b.name))) {
    const aliases = cmd.aliases?.length ? ` (${cmd.aliases.join(', ')})` : '';
    const usage = compactUsage(cmd);
    const desc = cmd.description ? ` — ${cmd.description}` : '';
    lines.push(`- \`${usage}\`${aliases}${desc}`);
  }
  return lines;
}

function emitTerseLines(cmds) {
  const lines = [];
  for (const cmd of cmds.slice().sort((a, b) => a.name.localeCompare(b.name))) {
    const aliases = cmd.aliases?.length ? ` (${cmd.aliases.join(', ')})` : '';
    const desc = cmd.description ? ` — ${firstSentence(cmd.description)}` : '';
    lines.push(`- \`${cmd.name}\`${aliases}${desc}`);
  }
  return lines;
}

function emitTierSection(lines, tierKey, categoryOrder, groupsByTierCat) {
  const heading = TIER_HEADINGS[tierKey];
  lines.push(`## ${heading}`);
  lines.push('');
  if (tierKey === 'core') {
    lines.push('Working set for most cards; full usage on each line.');
  } else if (tierKey === 'microscope') {
    lines.push('Rarely needed; use `mc <command> --help` for args and examples.');
  }
  lines.push('');

  const seenCats = new Set();
  for (const cat of categoryOrder) {
    const cmds = groupsByTierCat[tierKey]?.[cat];
    if (!cmds?.length) continue;
    seenCats.add(cat);
    lines.push(`### ${cat}`);
    lines.push('');
    lines.push(...(tierKey === 'microscope' ? emitTerseLines(cmds) : emitFullLines(cmds)));
    lines.push('');
  }
  for (const [cat, cmds] of Object.entries(groupsByTierCat[tierKey] || {})) {
    if (seenCats.has(cat)) continue;
    lines.push(`### ${cat}`);
    lines.push('');
    lines.push(...(tierKey === 'microscope' ? emitTerseLines(cmds) : emitFullLines(cmds)));
    lines.push('');
  }
}

/**
 * @param {import('../bot/cli/registry.mjs').RAW_COMMAND_DEFS extends infer U ? U extends (infer V)[] ? V[] : never : never} rawDefs
 */
export function buildCheatsheet(rawDefs, categoryOrder = CATEGORY_ORDER) {
  /** @type {Record<string, Record<string, typeof rawDefs>>} */
  const groupsByTierCat = {};
  for (const tier of TIER_ORDER) {
    groupsByTierCat[tier] = {};
  }
  for (const cmd of rawDefs) {
    const tier = tierOf(cmd);
    const bucket = groupsByTierCat[tier] ?? groupsByTierCat.extended;
    if (!bucket[cmd.category]) bucket[cmd.category] = [];
    bucket[cmd.category].push(cmd);
  }

  const lines = [];
  lines.push('# mc command cheatsheet');
  lines.push('');
  lines.push('One line per command. Use `mc <command> --help` for full detail (args, types, examples).');
  lines.push('');
  lines.push('Generated by `scripts/gen-mc-cheatsheet.mjs` from `bot/cli/registry.mjs`. Do not edit by hand.');
  lines.push('');

  for (const tier of TIER_ORDER) {
    emitTierSection(lines, tier, categoryOrder, groupsByTierCat);
  }

  return lines.join('\n');
}

async function main() {
  const { RAW_COMMAND_DEFS, CATEGORY_ORDER } = await import(join(ROOT, 'bot/cli/registry.mjs'));
  const text = buildCheatsheet(RAW_COMMAND_DEFS, CATEGORY_ORDER);
  writeFileSync(CHEATSHEET_PATH, text);
  const categories = new Set(RAW_COMMAND_DEFS.map((c) => c.category)).size;
  const coreN = RAW_COMMAND_DEFS.filter((c) => tierOf(c) === 'core').length;
  console.log(
    `wrote ${CHEATSHEET_PATH} (${RAW_COMMAND_DEFS.length} commands, ${coreN} core, ${categories} categories)`,
  );
}

const invokedAsScript = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedAsScript) {
  await main();
}
