#!/usr/bin/env node
/**
 * Generate docs/mc-cheatsheet.md from bot/cli/registry.mjs.
 *
 * One line per command, grouped by category. Skills include this as the
 * canonical "what mc verbs exist" reference; per-command detail is fetched
 * on demand via `mc <cmd> --help`. This keeps the agent's prompt small.
 *
 * Run:   node scripts/gen-mc-cheatsheet.mjs
 * Output: docs/mc-cheatsheet.md
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { RAW_COMMAND_DEFS } = await import(join(ROOT, 'bot/cli/registry.mjs'));

// Display order — most-touched categories first.
const CATEGORY_ORDER = ['observe', 'movement', 'world', 'craft', 'combat', 'memory', 'goals', 'task', 'social', 'platform'];

function compactUsage(cmd) {
  if (cmd.usage) return cmd.usage;
  if (cmd.argSchema?.length) {
    const parts = cmd.argSchema.map((a) => {
      const placeholder = a.key.toUpperCase();
      return a.required ? placeholder : `[${placeholder}]`;
    });
    return `mc ${cmd.name} ${parts.join(' ')}`.trim();
  }
  return `mc ${cmd.name}`;
}

const groups = {};
for (const cmd of RAW_COMMAND_DEFS) {
  if (!groups[cmd.category]) groups[cmd.category] = [];
  groups[cmd.category].push(cmd);
}

const lines = [];
lines.push('# mc command cheatsheet');
lines.push('');
lines.push('One line per command. Use `mc <command> --help` for full detail (args, types, examples).');
lines.push('');
lines.push('Generated by `scripts/gen-mc-cheatsheet.mjs` from `bot/cli/registry.mjs`. Do not edit by hand.');
lines.push('');

const seenCats = new Set();
for (const cat of CATEGORY_ORDER) {
  if (!groups[cat]) continue;
  seenCats.add(cat);
  lines.push(`## ${cat}`);
  lines.push('');
  for (const cmd of groups[cat].sort((a, b) => a.name.localeCompare(b.name))) {
    const aliases = cmd.aliases?.length ? ` (${cmd.aliases.join(', ')})` : '';
    const usage = compactUsage(cmd);
    const desc = cmd.description ? ` — ${cmd.description}` : '';
    lines.push(`- \`${usage}\`${aliases}${desc}`);
  }
  lines.push('');
}

// Catch any categories not in CATEGORY_ORDER.
for (const [cat, cmds] of Object.entries(groups)) {
  if (seenCats.has(cat)) continue;
  lines.push(`## ${cat}`);
  lines.push('');
  for (const cmd of cmds.sort((a, b) => a.name.localeCompare(b.name))) {
    const aliases = cmd.aliases?.length ? ` (${cmd.aliases.join(', ')})` : '';
    const usage = compactUsage(cmd);
    const desc = cmd.description ? ` — ${cmd.description}` : '';
    lines.push(`- \`${usage}\`${aliases}${desc}`);
  }
  lines.push('');
}

const out = join(ROOT, 'docs/mc-cheatsheet.md');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out} (${RAW_COMMAND_DEFS.length} commands across ${Object.keys(groups).length} categories)`);
