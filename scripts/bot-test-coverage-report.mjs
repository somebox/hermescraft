#!/usr/bin/env node
/**
 * Cross-check mc registry commands vs bot/test and tests/functional coverage.
 * Emits docs/reference/audits/bot-test-coverage-YYYY-MM-DD.md
 *
 * Usage:
 *   node scripts/bot-test-coverage-report.mjs
 *   node scripts/bot-test-coverage-report.mjs --check   # exit 1 if P0 commands lack strong+contract
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..');
const BOT_TEST = path.join(REPO, 'bot', 'test');
const FUNC_TEST = path.join(REPO, 'tests', 'functional');

const { RAW_COMMAND_DEFS } = await import(path.join(REPO, 'bot', 'cli', 'registry.mjs'));

const HOT_PATH = new Set([
  'dig', 'collect', 'place', 'craft', 'chest', 'deposit', 'withdraw',
  'goto', 'goto_near', 'move', 'escape', 'pillar_up', 'pillar_down', 'smelt',
  'fight', 'observe', 'status', 'scene', 'nearby', 'mark', 'go_mark', 'regions',
  'construct', 'blueprint_repair', 'blueprint', 'region_check',
]);

/** P0 — must reach strong + contract in bot/test after audit work */
const P0_COMMANDS = new Set([
  'screenshot_meta', 'playbook_phase_clear',
  'poi_add', 'poi_update', 'go_poi', 'unpoi', 'poi_check_torch',
]);

const AMBIGUOUS = new Set(['status', 'check', 'path', 'level', 'crit', 'mark', 'goals', 'goal']);

function walk(dir, acc = [], ext = '.test.js') {
  if (!fs.existsSync(dir)) return acc;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, acc, ext);
    else if (e.name.endsWith(ext)) acc.push(p);
  }
  return acc;
}

function strongRefs(name, content) {
  const needles = [
    `actions.${name}(`,
    `.${name}({`,
    `.${name}()`,
    `/action/${name}`,
    `handler): ${name}`,
    `audit smoke (action handler): ${name}`,
    `POST /action/${name}`,
  ];
  if (needles.some((n) => content.includes(n))) return true;
  return new RegExp(`test\\([^)]*\\b${name}\\b`).test(content);
}

function weakRef(name, content) {
  if (strongRefs(name, content)) return false;
  return new RegExp(`\\b${name}\\b`).test(content);
}

function hasContractAssertions(content) {
  return /assertFailure|assertContract|\bvalidate\s*\(/.test(content);
}

function classifyCommand(def, nodeFiles, funcFiles) {
  const name = def.name;
  let strong = [];
  let weak = [];
  let contract = [];
  let auditSmoke = false;

  for (const { rel, content } of nodeFiles) {
    if (strongRefs(name, content)) {
      strong.push(rel);
      if (hasContractAssertions(content)) contract.push(rel);
      if (rel === 'commands-audit-coverage.test.js') auditSmoke = true;
    } else if (weakRef(name, content)) {
      weak.push(rel);
    }
  }

  const pytest = funcFiles.filter(({ content }) =>
    new RegExp(`\\b${name}\\b|mc ${name}|/action/${name}`).test(content),
  ).map((f) => f.rel);

  const libraryOnly =
    name === 'blueprint' &&
    strong.length === 0 &&
    nodeFiles.some(
      (f) => f.rel.includes('runtime/blueprints/') && f.content.includes('verify'),
    );

  let tier = 'none';
  if (contract.length > 0) tier = 'contract';
  else if (strong.length > 0) tier = 'strong';
  else if (pytest.length > 0) tier = 'pytest-only';
  else if (weak.length > 0) tier = 'weak';
  else if (libraryOnly) tier = 'library-only';

  if (auditSmoke && tier !== 'contract' && strong.length <= 1) tier = 'audit-smoke';

  return {
    name,
    category: def.category,
    method: def.method,
    tier,
    strongCount: strong.length,
    weakCount: weak.length,
    contractCount: contract.length,
    pytestCount: pytest.length,
    strongFiles: strong.slice(0, 4),
    ambiguous: AMBIGUOUS.has(name),
  };
}

function main() {
  const nodePaths = walk(BOT_TEST);
  const nodeFiles = nodePaths.map((f) => ({
    rel: path.relative(BOT_TEST, f),
    content: fs.readFileSync(f, 'utf8'),
  }));

  const funcPaths = walk(FUNC_TEST, [], '.py');
  const funcFiles = funcPaths.map((f) => ({
    rel: path.relative(FUNC_TEST, f),
    content: fs.readFileSync(f, 'utf8'),
  }));

  const rows = RAW_COMMAND_DEFS.map((d) => classifyCommand(d, nodeFiles, funcFiles));

  const byTier = {};
  for (const r of rows) {
    byTier[r.tier] = (byTier[r.tier] || 0) + 1;
  }

  const today = new Date().toISOString().slice(0, 10);
  const outPath = path.join(REPO, 'docs', 'reference', 'audits', `bot-test-coverage-${today}.md`);

  const lines = [
    `# Bot test coverage matrix — ${today}`,
    '',
    'Generated by `node scripts/bot-test-coverage-report.mjs`. Registry: `bot/cli/registry.mjs`.',
    '',
    '## Summary',
    '',
    `| Metric | Value |`,
    `|--------|-------|`,
    `| Registry commands | ${rows.length} |`,
    ...Object.entries(byTier)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([t, n]) => `| Tier \`${t}\` | ${n} |`),
    '',
    '### Tier definitions',
    '',
    '- **contract** — strong handler/route ref in a test file that uses `assertContract` / `assertFailure` / `validate(`',
    '- **strong** — explicit handler invocation or audit smoke title, no contract asserts in that file',
    '- **weak** — word match only (may be false positive for ambiguous verbs)',
    '- **audit-smoke** — primarily `commands-audit-coverage.test.js`',
    '- **pytest-only** — functional test reference, no strong Node ref',
    '- **library-only** — blueprint verify library without action handler test',
    '- **none** — no Node or pytest match',
    '',
    '## Hot-path appendix (L0 + building)',
    '',
    '| Command | Tier | Node strong | Contract files | Pytest |',
    '|---------|------|-------------|----------------|--------|',
  ];

  for (const name of [...HOT_PATH].sort()) {
    const r = rows.find((x) => x.name === name);
    if (!r) continue;
    lines.push(
      `| \`${name}\` | ${r.tier} | ${r.strongCount} | ${r.contractCount} | ${r.pytestCount} |`,
    );
  }

  lines.push('', '## Tier-3 gaps (Node cannot satisfy L0 alone)', '');
  lines.push('| Command | Node tier | Pytest refs | Note |');
  lines.push('|---------|-----------|-------------|------|');
  const tier3Notes = [
    ['smelt', 'Node furnace-contract; pytest 0', 'Add functional smelt when changing furnace handlers'],
    ['pillar_up', 'Many Node regressions', 'Functional uses legacy pillar_step naming'],
    ['pillar_down', 'Node excavation/pillar tests', 'Sparse pytest'],
    ['craft', 'crafting-contract', '~1 functional hit — L0 crafted_count lives in pytest'],
    ['go_mark', 'Nav tests, no contract file', 'No dedicated functional module'],
    ['scene', 'scene-*.test.js shape', 'GET route envelope thin'],
  ];
  for (const [cmd, note, detail] of tier3Notes) {
    const r = rows.find((x) => x.name === cmd);
    lines.push(`| \`${cmd}\` | ${r?.tier ?? 'n/a'} | ${r?.pytestCount ?? 0} | ${detail} |`);
  }

  lines.push('', '## Full command table', '');
  lines.push('| Category | Command | Method | Tier | Strong | Contract | Pytest | Ambiguous |');
  lines.push('|----------|---------|--------|------|--------|----------|--------|-----------|');
  for (const r of rows) {
    lines.push(
      `| ${r.category} | \`${r.name}\` | ${r.method} | ${r.tier} | ${r.strongCount} | ${r.contractCount} | ${r.pytestCount} | ${r.ambiguous ? 'yes' : ''} |`,
    );
  }

  lines.push('');
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, lines.join('\n'));
  console.log(`Wrote ${outPath}`);

  if (process.argv.includes('--check')) {
    /** No HTTP handler; CLI/registry coverage is sufficient. */
    const P0_CLI_ONLY = new Set(['screenshot_meta']);
    const p0Fail = [...P0_COMMANDS].filter((name) => {
      if (P0_CLI_ONLY.has(name)) {
        const r = rows.find((x) => x.name === name);
        return !r || (r.strongCount === 0 && r.weakCount === 0);
      }
      const r = rows.find((x) => x.name === name);
      return !r || r.contractCount === 0;
    });
    if (p0Fail.length) {
      console.error('P0 commands without contract-tier coverage:', p0Fail.join(', '));
      process.exit(1);
    }
  }
}

main();
